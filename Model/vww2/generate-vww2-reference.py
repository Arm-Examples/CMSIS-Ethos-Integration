"""Generate firmware test vectors from the ML Zoo VWW-2 NumPy files."""

from pathlib import Path

import numpy as np


root = Path(__file__).resolve().parent
input_data = np.load(root / "reference_input.npy", allow_pickle=False)
output_data = np.load(root / "reference_output.npy", allow_pickle=False)
if input_data.shape != (1, 50, 50, 1) or input_data.dtype != np.int8:
    raise ValueError("unexpected VWW-2 reference input metadata")
if output_data.shape != (1, 2) or output_data.dtype != np.int8:
    raise ValueError("unexpected VWW-2 reference output metadata")


def array(name: str, values: np.ndarray) -> str:
    numbers = [int(value) for value in values.flat]
    rows = ["  " + ", ".join(f"{number:4d}" for number in numbers[i:i + 16]) + ","
            for i in range(0, len(numbers), 16)]
    return f"const int8_t {name}[{len(numbers)}] = {{\n" + "\n".join(rows) + "\n};\n"


content = (
    "/* Generated by generate-vww2-reference.py from ML Zoo reference arrays.\n"
    " * Source: Arm-Examples/ML-zoo, commit fec0bb5bcd486eb2839cdb7d437d466067402a6a\n"
    " * SPDX-License-Identifier: Apache-2.0\n */\n"
    '#include "reference_data.h"\n\n'
    + array("vww2_reference_input", input_data)
    + "\n"
    + array("vww2_reference_output", output_data)
)
(root / "reference_data.c").write_text(content, encoding="utf-8", newline="\n")
